"""治理层：签名与晋升（V3 版 promote + V2 版 promote_yaml）。"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass

import yaml

from ..semantic.layer import SemanticLayer
from .clustering import Cluster, heat


@dataclass(frozen=True)
class ReviewRecord:
    rid: str
    cid: str
    decided_by: str
    decision: str  # promote / reject / merge
    chosen_sql: str
    note: str
    decided_at: str


def promote(
    cluster: Cluster, rec: ReviewRecord, sem: SemanticLayer, today: str = "2026-10-30"
) -> str:
    """D7：evidence 快照自包含——raw log 一年后删除，审计仍可回答“指标哪来的”"""
    h = heat(cluster, today)
    if rec.decision != "promote":
        raise ValueError("只有 decision=promote 能晋升")
    name = cluster.sig.metric
    digest = hashlib.sha256(
        json.dumps(sorted(cluster.variants), ensure_ascii=False).encode()
    ).hexdigest()[:12]
    entry = {
        "name": name,
        "desc": f"{name}（由持续运营机制晋升，签名 {cluster.sig.key()}）",
        "unit": "ratio",
        "dims": list(cluster.sig.dims) or ["channel"],
        "calc": name,
        "owner": rec.decided_by,
        "signed_at": rec.decided_at,
        "aliases": sorted(cluster.variants),  # 问法聚类回填 alias（D1 收益）
        "provenance": {  # D7：自包含证据快照
            "promoted_at": rec.decided_at,
            "owner": rec.decided_by,
            "evidence_snapshot": {
                "n_queries": h["n_queries"],
                "n_users": h["n_users"],
                "window": f"{today} 前 30 天",
                "question_variants": sorted(cluster.variants),
                "sql_selected": rec.chosen_sql,
                "variants_digest": digest,
                "review_record": rec.rid,
            },
        },
        "changelog": [
            {
                "date": rec.decided_at,
                "version": "v1.0",
                "note": f"持续运营晋升（{rec.rid}）：{rec.note}",
            }
        ],
    }
    cfg = yaml.safe_load(sem.to_yaml())
    cfg["metrics"] = [m for m in cfg["metrics"] if m["name"] != name] + [entry]
    return yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False)


def promote_yaml(candidates: list[dict], decisions: dict) -> str:
    """签字闸：Owner 未签字的指标行，禁止合入正式 YAML（V1 同款纪律）"""
    out = ["# generated by excavate.py —— Owner 逐条签字后方可合入", 'version: "2.0"', "metrics:"]
    for c in candidates:
        d = decisions.get(c["metric"])
        if not d or not d.get("signed_by"):
            out.append(f"  # [BLOCKED] {c['metric']}: 无 Owner 签字，禁止合入")
            continue
        out.append(
            f"  - name: {c['metric']}\n"
            f"    expr: {d['final_expr']}\n"
            f"    owner: {d['signed_by']}\n"
            f"    signed_at: {d['signed_at']}"
        )
    return "\n".join(out)
